function show(h) {
  let id = h || "home";
  let t = null;

  if (id.startsWith("tour-")) {
    t = tour(id.slice(5));
    id = t ? "tour" : "home";
  } else if (!N[id]) {
    id = "home";
  }

  cur = id;
  $$(".pg").forEach((s) => { s.hidden = s.id !== "p-" + id; });

  /* Подсветка активного пункта меню */
  $$("#nv a").forEach((a) => {
    const href = a.getAttribute("href");
    href === "#" + (id === "tour" ? "tours" : id)
      ? a.setAttribute("aria-current", "page")
      : a.removeAttribute("aria-current");
  });

  hd.classList.remove("o");
  $("#mb").setAttribute("aria-expanded", "false");
  document.title = (t ? t.n : N[id]) + " — Kaz Travel";
  hs();
  window.scrollTo(0, 0);
}

